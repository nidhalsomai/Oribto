function resolveLang(?string $storedLang = null): string
{
    $preferred = $_COOKIE['orbito_lang'] ?? null;
    if ($preferred && isset($GLOBALS['LANG'][$preferred])) {
        return $preferred;
    }

    if ($storedLang && isset($GLOBALS['LANG'][$storedLang])) {
        return $storedLang;
    }

    return 'en';
}

function t(string $key, ?string $lang = null): string
{
    $lang = $lang ?? resolveLang();
    $fallback = $GLOBALS['LANG']['en'][$key] ?? $key;
    return $GLOBALS['LANG'][$lang][$key] ?? $fallback;
}